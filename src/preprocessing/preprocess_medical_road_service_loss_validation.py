#!/usr/bin/env python3
"""Preprocessing script for data/exp/road-service-loss-validation/technical_scenario_results.csv
Output: data/processed/road-service-loss/medical_road_service_loss_validation_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/road-service-loss-validation/technical_scenario_results.csv"
dst = ROOT / "data/processed/road-service-loss/medical_road_service_loss_validation_preprocessed.parquet"

# --- Load ---
df = pd.read_csv(src, encoding="utf-8-sig", low_memory=False)

# --- Select and rename columns ---
rename_map = {
    "Lost Medical Path Population": "Lost Medical Path Population",
    "Additional Medical Distance Burden": "Additional Medical Distance Burden",
    "Disconnected Mesh Count": "Disconnected Mesh Count",
    "Remaining Reachable Population": "Remaining Reachable Population",
    "Mesh Count With Additional Distance": "Mesh Count With Additional Distance",
    "Maximum Additional Distance": "Maximum Additional Distance",
    "Numerical Distance Tolerance": "Numerical Distance Tolerance",
    "Validation Case": "Validation Case",
    "Candidate Road Source Record": "Candidate Road Source Record",
    "Closed Source Edge ID": "Closed Source Edge ID",
    "Closed Source Length": "Closed Source Length",
    "Closed Origin Entry Population": "Closed Origin Entry Population",
    "Closed Medical Entry Count": "Closed Medical Entry Count",
    "Scenario Runtime Seconds": "Scenario Runtime Seconds",
    "Result Role": "Result Role",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
