src = ROOT / "data/exp/demographic-stability/priority_stability_construction.parquet"
dst = ROOT / "data/processed/demographic-stability/priority_stability_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Population-Change Scenario": "Population-Change Scenario",
    "Budget Share": "Budget Share",
    "Priority Stability": "Priority Stability",
    "Intersection Unit Count": "Intersection Unit Count",
    "Union Unit Count": "Union Unit Count",
    "Selected Maintenance Unit Count": "Selected Maintenance Unit Count",
    "Reference Selected Unit Count": "Reference Selected Unit Count",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
