#!/usr/bin/env python3
"""Preprocessing script for data/exp/national-population-entry/point_attachment_diagnostics.csv
Output: data/processed/medical-baseline/medical_facilities_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from medical_baseline_io import verify_source, verify_saved
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/national-population-entry/point_attachment_diagnostics.csv"
dst = ROOT / "data/processed/medical-baseline/medical_facilities_preprocessed.parquet"

# --- Load ---
verify_source(src)
df = pd.read_csv(src, dtype={"point_id": str, "category": str, "source_id": str, "name": str}, keep_default_na=False, low_memory=False)
df = df.loc[df.dataset.eq("medical")].copy()

# --- Select and rename columns ---
rename_map = {
    "point_id": "Medical Facility ID",
    "dataset": "Source Dataset",
    "category": "Medical Facility Category",
    "name": "Medical Facility Name",
    "source_id": "Medical Facility Source Record",
    "longitude": "Longitude",
    "latitude": "Latitude",
    "routing_eligible": "Candidate Road Entry Eligible",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)


df["Selected Medical Destination"] = df["Medical Facility Category"].isin(["1", "2"])
df["Included Medical Network Destination"] = df["Selected Medical Destination"] & df["Candidate Road Entry Eligible"]
# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")

verify_saved(df, dst)
