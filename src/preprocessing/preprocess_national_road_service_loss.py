#!/usr/bin/env python3
"""Preprocessing script for data/exp/national-road-service-loss/national_road_service_loss.parquet
Output: data/processed/road-service-loss/national_road_service_loss_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/national-road-service-loss/national_road_service_loss.parquet"
dst = ROOT / "data/processed/road-service-loss/national_road_service_loss_preprocessed.parquet"

# --- Load ---
receipt = json.loads((src.parent / "validation.json").read_text())
assert receipt["status"] == "passed" and receipt["national_complete"], "National computation is incomplete"
df = pd.read_parquet(src)
assert len(df) == receipt["source_road_rows"]

# --- Select and rename columns ---
rename_map = {
    "Graph Source Edge ID": "Graph Source Edge ID",
    "Lost Medical Path Population": "Lost Medical Path Population",
    "Additional Medical Distance Burden": "Additional Medical Distance Burden",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
