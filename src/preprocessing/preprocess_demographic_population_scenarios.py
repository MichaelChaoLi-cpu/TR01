from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/demographic-stability/population_scenarios_construction.parquet"
dst = ROOT / "data/processed/demographic-stability/population_scenarios_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Publication Support Code": "Publication Support Code",
    "Local Total Population": "Local Total Population",
    "Higher Ageing Area": "Higher Ageing Area",
    "Baseline Distance Disadvantaged Area": "Baseline Distance Disadvantaged Area",
    "Forecast Matched Origin": "Forecast Matched Origin",
    "Population-Change Scenario": "Population-Change Scenario",
    "Forecast Reference Population": "Forecast Reference Population",
    "Projected Total Population": "Projected Total Population",
    "Population Change Factor": "Population Change Factor",
    "Scenario Population": "Scenario Population",
    "Ageing Scenario": "Ageing Scenario",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
