#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/road-traffic-comparison/accepted_crosswalk_construction_input.parquet
Output: data/processed/observed-traffic/accepted_traffic_road_crosswalk_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/road-traffic-comparison/accepted_crosswalk_construction_input.parquet"
dst = ROOT / "data/processed/observed-traffic/accepted_traffic_road_crosswalk_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Graph Source Edge ID": "Graph Source Edge ID",
    "Registry Group Index": "Registry Group Index",
    "Source Road Length": "Source Road Length",
    "Minimum Line Separation": "Minimum Line Separation",
    "Road Fraction Within Diagnostic Buffer": "Road Fraction Within Diagnostic Buffer",
    "Aligned Sample Fraction": "Aligned Sample Fraction",
    "Complete Observation Unit Geometry": "Complete Observation Unit Geometry",
    "Technical Proposal Qualified": "Technical Proposal Qualified",
    "N13 Road Level": "N13 Road Level",
    "N13 Road State": "N13 Road State",
    "Traffic Observation Key": "Traffic Observation Key",
    "Observed Traffic Volume": "Observed Traffic Volume",
    "Candidate Road Source Record": "Candidate Road Source Record",
    "Baseline Source Road Length": "Baseline Source Road Length",
    "Result Role": "Result Role",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
