#!/usr/bin/env python3
"""Preprocessing script for data/exp/national-pavement-policy-computation/national_pavement_rankings.parquet
Output: data/processed/national-pavement-policy/national_pavement_rankings_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/national-pavement-policy-computation/national_pavement_rankings.parquet"
dst = ROOT / "data/processed/national-pavement-policy/national_pavement_rankings_preprocessed.parquet"

import pyarrow as pa
import pyarrow.parquet as pq
dst.parent.mkdir(parents=True, exist_ok=True)
part = dst.with_suffix('.part')
writer = None
count = 0
try:
    for batch in pq.ParquetFile(src).iter_batches(batch_size=250000):
        df = batch.to_pandas()
        rename_map = {
            "Graph Source Edge ID": "Graph Source Edge ID",
            "Pavement Maintenance Priority": "Pavement Maintenance Priority",
            "Pavement Impedance Increment": "Pavement Impedance Increment",
            "Pavement Priority Rank": "Pavement Priority Rank",
            "Pavement Traffic Priority Score": "Pavement Traffic Priority Score",
            "Pavement Isolated Restoration Gain": "Pavement Isolated Restoration Gain",
            "Pavement Access Priority Score": "Pavement Access Priority Score",
            "Pavement Relative Maintenance Cost": "Pavement Relative Maintenance Cost",
        }
        df = df[list(rename_map.keys())].rename(columns=rename_map)
        table = pa.Table.from_pandas(df, preserve_index=False)
        if writer is None:
            writer = pq.ParquetWriter(part, table.schema, compression='zstd')
        writer.write_table(table)
        count += len(df)
finally:
    if writer is not None:
        writer.close()
part.replace(dst)
assert pq.ParquetFile(dst).metadata.num_rows == count
print(f'Saved {count:,} readable rows: {dst.relative_to(ROOT)}', flush=True)
