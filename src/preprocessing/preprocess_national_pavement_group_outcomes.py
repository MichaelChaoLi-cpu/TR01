#!/usr/bin/env python3
"""Preprocessing script for data/exp/national-pavement-policy-computation/national_pavement_group_outcomes.parquet
Output: data/processed/national-pavement-policy/national_pavement_group_outcomes_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/national-pavement-policy-computation/national_pavement_group_outcomes.parquet"
dst = ROOT / "data/processed/national-pavement-policy/national_pavement_group_outcomes_preprocessed.parquet"

import pyarrow as pa
import pyarrow.parquet as pq
dst.parent.mkdir(parents=True, exist_ok=True)
part = dst.with_suffix('.part')
writer = None
count = 0
try:
    for batch in pq.ParquetFile(src).iter_batches(batch_size=250000):
        df = batch.to_pandas()
        rename_map = {
            "Pavement Impedance Increment": "Pavement Impedance Increment",
            "Pavement Maintenance Priority": "Pavement Maintenance Priority",
            "Pavement Budget Share": "Pavement Budget Share",
            "Pavement Population Group": "Pavement Population Group",
            "Pavement Reference Access Burden": "Pavement Reference Access Burden",
            "Pavement Residual Access Burden": "Pavement Residual Access Burden",
            "Pavement Avoided Access Burden": "Pavement Avoided Access Burden",
            "Pavement Access Protection Share": "Pavement Access Protection Share",
            "Pavement Requested Relative Budget": "Pavement Requested Relative Budget",
            "Pavement Actual Relative Spending": "Pavement Actual Relative Spending",
            "Pavement Unused Relative Budget": "Pavement Unused Relative Budget",
            "Pavement Actual Spending Share": "Pavement Actual Spending Share",
            "Pavement Unused Budget Share": "Pavement Unused Budget Share",
            "Pavement Selected Road Count": "Pavement Selected Road Count",
        }
        df = df[list(rename_map.keys())].rename(columns=rename_map)
        table = pa.Table.from_pandas(df, preserve_index=False)
        if writer is None:
            writer = pq.ParquetWriter(part, table.schema, compression='zstd')
        writer.write_table(table)
        count += len(df)
finally:
    if writer is not None:
        writer.close()
part.replace(dst)
assert pq.ParquetFile(dst).metadata.num_rows == count
print(f'Saved {count:,} readable rows: {dst.relative_to(ROOT)}', flush=True)
