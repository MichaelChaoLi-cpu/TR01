#!/usr/bin/env python3
"""Preprocessing script for data/processed/medical-baseline/medical_mesh_baseline.parquet
Output: data/processed/medical-analysis-sample/medical_mesh_analysis_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/medical-baseline/medical_mesh_baseline.parquet"
dst = ROOT / "data/processed/medical-analysis-sample/medical_mesh_analysis_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# Age is observed on official publication supports, not imputed to meshes.
# Apply the human-selected support exclusion to every associated mesh.
age = pd.read_parquet(ROOT / "data/processed/medical-baseline/medical_age_support_baseline.parquet")
valid_age_supports = age.loc[
    age["Population Aged 65+ Share Among Known Ages"].notna(),
    "Publication Support Code",
]
df = df.loc[df["Publication Support Code"].isin(valid_age_supports)]

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Publication Support Code": "Publication Support Code",
    "Suppression Status": "Suppression Status",
    "Local Total Population": "Local Total Population",
    "Candidate Medical Network Distance": "Candidate Medical Network Distance",
    "Candidate Road Entry Eligible": "Candidate Road Entry Eligible",
    "Candidate Road Source Record": "Candidate Road Source Record",
    "Medical Route Status": "Medical Route Status",
    "Candidate Road Entry Method": "Candidate Road Entry Method",
    "Longitude": "Longitude",
    "Latitude": "Latitude",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Variable-level preprocessing ---
# Candidate Medical Network Distance
df = df.dropna(subset=["Candidate Medical Network Distance"])

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
