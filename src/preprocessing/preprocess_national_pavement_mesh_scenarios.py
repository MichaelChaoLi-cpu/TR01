#!/usr/bin/env python3
"""Preprocessing script for data/exp/national-pavement-policy-computation/national_pavement_mesh_scenarios.parquet
Output: data/processed/national-pavement-policy/national_pavement_mesh_scenarios_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/national-pavement-policy-computation/national_pavement_mesh_scenarios.parquet"
dst = ROOT / "data/processed/national-pavement-policy/national_pavement_mesh_scenarios_preprocessed.parquet"

import pyarrow as pa
import pyarrow.parquet as pq
dst.parent.mkdir(parents=True, exist_ok=True)
part = dst.with_suffix('.part')
writer = None
count = 0
try:
    for batch in pq.ParquetFile(src).iter_batches(batch_size=250000):
        df = batch.to_pandas()
        rename_map = {
            "Mesh Code": "Mesh Code",
            "Local Total Population": "Local Total Population",
            "Candidate Medical Network Distance": "Candidate Medical Network Distance",
            "Longitude": "Longitude",
            "Latitude": "Latitude",
            "Pavement Impedance Increment": "Pavement Impedance Increment",
            "Pavement Maintenance Priority": "Pavement Maintenance Priority",
            "Pavement Budget Share": "Pavement Budget Share",
            "Pavement Medical Access Cost": "Pavement Medical Access Cost",
            "Pavement Medical Access Cost Increase": "Pavement Medical Access Cost Increase",
        }
        df = df[list(rename_map.keys())].rename(columns=rename_map)
        table = pa.Table.from_pandas(df, preserve_index=False)
        if writer is None:
            writer = pq.ParquetWriter(part, table.schema, compression='zstd')
        writer.write_table(table)
        count += len(df)
finally:
    if writer is not None:
        writer.close()
part.replace(dst)
assert pq.ParquetFile(dst).metadata.num_rows == count
print(f'Saved {count:,} readable rows: {dst.relative_to(ROOT)}', flush=True)
