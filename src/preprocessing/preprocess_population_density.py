from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/processed/population-density/population_density_constructed.parquet"
dst = ROOT / "data/processed/population-density/population_density_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Publication Support Code": "Publication Support Code",
    "Member Mesh Count": "Member Mesh Count",
    "Support Total Population": "Support Total Population",
    "Support Footprint Area": "Support Footprint Area",
    "Population Density": "Population Density",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
