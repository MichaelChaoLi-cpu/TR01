#!/usr/bin/env python3
"""Preprocessing script for data/exp/pavement-policy-computation/pavement_selections.parquet
Output: data/processed/pavement-policy/pavement_selections_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/pavement-policy-computation/pavement_selections.parquet"
dst = ROOT / "data/processed/pavement-policy/pavement_selections_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Graph Source Edge ID": "Graph Source Edge ID",
    "Pavement Maintenance Priority": "Pavement Maintenance Priority",
    "Pavement Budget Share": "Pavement Budget Share",
    "Pavement Maintenance Selected": "Pavement Maintenance Selected",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# Approved baseline-increment cost derivative; complete selections stay fixed.
roads = pd.read_parquet(ROOT / "data/processed/pavement-common-sample/pavement_common_sample_preprocessed.parquet",
                        columns=["Graph Source Edge ID", "Pavement Relative Maintenance Cost"])
costs = df["Graph Source Edge ID"].map(roads.set_index("Graph Source Edge ID")["Pavement Relative Maintenance Cost"])
assert costs.notna().all()
df["Pavement Impedance Increment"] = 0.25
df["Pavement Effective Road Cost"] = costs * (1 + 0.25 * (~df["Pavement Maintenance Selected"]))
assert len(df) == 70049 * 12

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
