#!/usr/bin/env python3
"""Preprocessing script for data/exp/national-population-entry/population_path_diagnostics.csv
Output: data/processed/medical-baseline/medical_mesh_distances_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from medical_baseline_io import verify_source, verify_saved
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/national-population-entry/population_path_diagnostics.csv"
dst = ROOT / "data/processed/medical-baseline/medical_mesh_distances_preprocessed.parquet"

# --- Load ---
verify_source(src)
df = pd.read_csv(src, dtype={"mesh_code": str, "road_source_id": str}, low_memory=False, float_precision="round_trip")
df = df.loc[df.target.eq("medical")].copy()

# --- Select and rename columns ---
rename_map = {
    "mesh_code": "Mesh Code",
    "target": "Service Target",
    "network_distance_m": "Candidate Medical Network Distance",
    "routing_eligible": "Candidate Road Entry Eligible",
    "road_source_id": "Candidate Road Source Record",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)


# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")

verify_saved(df, dst)
