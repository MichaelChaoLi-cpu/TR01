#!/usr/bin/env python3
"""Preprocessing script for data/exp/pavement-policy-computation/pavement_mesh_scenarios.parquet
Output: data/processed/pavement-policy/pavement_mesh_scenarios_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/pavement-policy-computation/pavement_mesh_scenarios.parquet"
dst = ROOT / "data/processed/pavement-policy/pavement_mesh_scenarios_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Local Total Population": "Local Total Population",
    "Candidate Medical Network Distance": "Candidate Medical Network Distance",
    "Longitude": "Longitude",
    "Latitude": "Latitude",
    "Pavement Impedance Increment": "Pavement Impedance Increment",
    "Pavement Maintenance Priority": "Pavement Maintenance Priority",
    "Pavement Budget Share": "Pavement Budget Share",
    "Pavement Medical Access Cost": "Pavement Medical Access Cost",
    "Pavement Medical Access Cost Increase": "Pavement Medical Access Cost Increase",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
