#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/national-pavement-inputs/national_pavement_inputs.parquet
Output: data/processed/national-pavement-inputs/national_pavement_inputs_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/national-pavement-inputs/national_pavement_inputs.parquet"
dst = ROOT / "data/processed/national-pavement-inputs/national_pavement_inputs_preprocessed.parquet"

import pyarrow as pa
import pyarrow.parquet as pq
dst.parent.mkdir(parents=True, exist_ok=True)
part = dst.with_suffix('.part')
writer = None
count = 0
try:
    for batch in pq.ParquetFile(src).iter_batches(batch_size=250000):
        df = batch.to_pandas()
        rename_map = {
            "Graph Source Edge ID": "Graph Source Edge ID",
            "Baseline Source Road Length": "Baseline Source Road Length",
            "Road Classification Code": "Road Classification Code",
            "Road Width Code": "Road Width Code",
            "Observed Traffic Volume": "Observed Traffic Volume",
            "Anchored Pavement Inspection Category": "Anchored Pavement Inspection Category",
            "Scenario Traffic Volume": "Scenario Traffic Volume",
            "Scenario Pavement Need Category": "Scenario Pavement Need Category",
            "Scenario Traffic Basis": "Scenario Traffic Basis",
            "Scenario Condition Basis": "Scenario Condition Basis",
            "Scenario Traffic Calibration Stratum": "Scenario Traffic Calibration Stratum",
            "Scenario Condition Calibration Stratum": "Scenario Condition Calibration Stratum",
            "Scenario Deterioration Eligible": "Scenario Deterioration Eligible",
            "Scenario Maintenance Eligible": "Scenario Maintenance Eligible",
            "Scenario Relative Maintenance Cost": "Scenario Relative Maintenance Cost",
            "Scenario Priority Tie Key": "Scenario Priority Tie Key",
        }
        df = df[list(rename_map.keys())].rename(columns=rename_map)
        table = pa.Table.from_pandas(df, preserve_index=False)
        if writer is None:
            writer = pq.ParquetWriter(part, table.schema, compression='zstd')
        writer.write_table(table)
        count += len(df)
finally:
    if writer is not None:
        writer.close()
part.replace(dst)
assert pq.ParquetFile(dst).metadata.num_rows == count
print(f'Saved {count:,} readable rows: {dst.relative_to(ROOT)}', flush=True)
