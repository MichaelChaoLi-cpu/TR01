#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/road-traffic-comparison/national_traffic_loss_construction_input.parquet
Output: data/processed/road-traffic-comparison/national_road_traffic_comparison_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/road-traffic-comparison/national_traffic_loss_construction_input.parquet"
dst = ROOT / "data/processed/road-traffic-comparison/national_road_traffic_comparison_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Graph Source Edge ID": "Graph Source Edge ID",
    "Observed Traffic Volume": "Observed Traffic Volume",
    "Lost Medical Path Population": "Lost Medical Path Population",
    "Additional Medical Distance Burden": "Additional Medical Distance Burden",
    "Traffic Observation Key": "Traffic Observation Key",
    "Traffic Match Status": "Traffic Match Status",
    "Baseline Source Road Length": "Baseline Source Road Length",
    "Closed Origin Entry Population": "Closed Origin Entry Population",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
