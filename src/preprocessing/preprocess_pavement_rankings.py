#!/usr/bin/env python3
"""Preprocessing script for data/exp/pavement-policy-computation/pavement_rankings.parquet
Output: data/processed/pavement-policy/pavement_rankings_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/pavement-policy-computation/pavement_rankings.parquet"
dst = ROOT / "data/processed/pavement-policy/pavement_rankings_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Graph Source Edge ID": "Graph Source Edge ID",
    "Pavement Relative Maintenance Cost": "Pavement Relative Maintenance Cost",
    "Observed Traffic Volume": "Observed Traffic Volume",
    "Anchored Pavement Inspection Category": "Anchored Pavement Inspection Category",
    "Pavement Impedance Increment": "Pavement Impedance Increment",
    "Pavement Maintenance Priority": "Pavement Maintenance Priority",
    "Pavement Traffic Priority Score": "Pavement Traffic Priority Score",
    "Pavement Isolated Restoration Gain": "Pavement Isolated Restoration Gain",
    "Pavement Access Priority Score": "Pavement Access Priority Score",
    "Pavement Priority Rank": "Pavement Priority Rank",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
